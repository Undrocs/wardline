package reports

import (
	"fmt"
	"io"
	"strings"

	"github.com/Undrocs/wardline/internal/findings"
)

// WriteMarkdown renders the report as Markdown suitable for pull request
// comments, artifacts or documentation.
func WriteMarkdown(w io.Writer, rep *Report) error {
	if rep == nil {
		return fmt.Errorf("no report")
	}
	var b strings.Builder

	fmt.Fprintf(&b, "# Wardline scan report\n\n")
	fmt.Fprintf(&b, "| Field | Value |\n|---|---|\n")
	fmt.Fprintf(&b, "| Target | `%s` |\n", escapeCell(rep.Scan.Target))
	fmt.Fprintf(&b, "| Mode | %s |\n", rep.Scan.Mode)
	fmt.Fprintf(&b, "| Files scanned | %d |\n", rep.Scan.Files)
	fmt.Fprintf(&b, "| Duration | %s |\n", humanDuration(rep.Scan.DurationMS))
	fmt.Fprintf(&b, "| Tool | %s %s |\n", rep.Tool.Name, rep.Tool.Version)
	fmt.Fprintf(&b, "| Configuration | %s |\n", escapeCell(orDefault(rep.Scan.ConfigFile, "built-in defaults")))
	fmt.Fprintf(&b, "| Network | %s |\n", networkSummary(rep))
	fmt.Fprintf(&b, "| Result | %s |\n\n", resultSummary(rep))

	fmt.Fprintf(&b, "## Summary\n\n")
	fmt.Fprintf(&b, "| Severity | Count |\n|---|---:|\n")
	c := rep.Summary.Counts
	for _, row := range []struct {
		name  string
		value int
	}{
		{"Critical", c.Critical}, {"High", c.High}, {"Medium", c.Medium},
		{"Low", c.Low}, {"Info", c.Info}, {"Unknown", c.Unknown},
	} {
		fmt.Fprintf(&b, "| %s | %d |\n", row.name, row.value)
	}
	fmt.Fprintf(&b, "| **Total** | **%d** |\n", rep.Summary.Total)
	if rep.Summary.Suppressed > 0 {
		fmt.Fprintf(&b, "| Suppressed | %d |\n", rep.Summary.Suppressed)
	}
	fmt.Fprintf(&b, "\n")

	fmt.Fprintf(&b, "## Scanners\n\n")
	fmt.Fprintf(&b, "| Scanner | Status | Scope | Findings |\n|---|---|---|---:|\n")
	for _, run := range rep.Scanners {
		status := string(run.Status)
		if run.Disabled {
			status = "disabled"
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %d |\n", run.Name, status, escapeCell(orDefault(run.Scope, "—")), run.Findings)
	}
	fmt.Fprintf(&b, "\n")
	if rep.Summary.Incomplete {
		fmt.Fprintf(&b, "> **This scan is incomplete.** Some checks were skipped or failed; the absence of findings does not mean the repository is clean.\n\n")
	}

	fmt.Fprintf(&b, "## Findings\n\n")
	live, suppressed := partitionSuppressed(rep.Findings)
	for _, f := range live {
		writeMarkdownFinding(&b, f)
	}
	if len(live) == 0 {
		fmt.Fprintf(&b, "No findings at or above the configured reporting threshold.\n\n")
	}

	if len(suppressed) > 0 {
		fmt.Fprintf(&b, "## Suppressed findings\n\n")
		fmt.Fprintf(&b, "| Rule | Location | Reason |\n|---|---|---|\n")
		for _, f := range suppressed {
			fmt.Fprintf(&b, "| %s | `%s` | %s |\n", f.RuleID, escapeCell(f.LocationString()), escapeCell(f.SuppressionReason))
		}
		fmt.Fprintf(&b, "\n")
	}

	if len(rep.PolicyNotices) > 0 {
		fmt.Fprintf(&b, "## Policy notices\n\n")
		for _, notice := range rep.PolicyNotices {
			fmt.Fprintf(&b, "- %s\n", notice)
		}
		fmt.Fprintf(&b, "\n")
	}

	var skipped []string
	for _, run := range rep.Scanners {
		if run.Disabled {
			continue
		}
		for _, sk := range run.Skipped {
			skipped = append(skipped, fmt.Sprintf("`%s` — %s: %s", sk.Check, run.Name, sk.Reason))
		}
		if run.Error != "" {
			skipped = append(skipped, fmt.Sprintf("`%s` scanner failed: %s", run.Name, run.Error))
		}
	}
	if len(skipped) > 0 {
		fmt.Fprintf(&b, "## Checks not completed\n\n")
		for _, s := range skipped {
			fmt.Fprintf(&b, "- %s\n", s)
		}
		fmt.Fprintf(&b, "\n")
	}
	if len(rep.Warnings) > 0 {
		fmt.Fprintf(&b, "## Warnings\n\n")
		for _, warning := range dedupe(rep.Warnings) {
			fmt.Fprintf(&b, "- %s\n", warning)
		}
		fmt.Fprintf(&b, "\n")
	}
	if len(rep.Errors) > 0 {
		fmt.Fprintf(&b, "## Errors\n\n")
		for _, e := range rep.Errors {
			fmt.Fprintf(&b, "- %s\n", e)
		}
		fmt.Fprintf(&b, "\n")
	}

	fmt.Fprintf(&b, "## Scan limitations\n\n")
	for _, limitation := range rep.Limitations {
		fmt.Fprintf(&b, "- %s\n", limitation)
	}
	fmt.Fprintf(&b, "\n---\n\nGenerated by Wardline %s. Severity and confidence are Wardline assessments; a clean scan does not guarantee security.\n", rep.Tool.Version)

	_, err := io.WriteString(w, b.String())
	return err
}

func writeMarkdownFinding(b *strings.Builder, f findings.Finding) {
	fmt.Fprintf(b, "### %s — %s\n\n", f.Severity.Label(), f.Title)
	fmt.Fprintf(b, "- **Rule:** `%s`\n", f.RuleID)
	fmt.Fprintf(b, "- **Scanner:** %s\n", f.Scanner)
	fmt.Fprintf(b, "- **Location:** `%s`\n", escapeCell(f.LocationString()))
	fmt.Fprintf(b, "- **Confidence:** %s\n", f.Confidence)
	if f.Evidence != "" {
		fence := codeFence(f.Evidence)
		fmt.Fprintf(b, "\n%stext\n%s\n%s\n\n", fence, f.Evidence, fence)
	}
	if f.Description != "" {
		fmt.Fprintf(b, "%s\n\n", f.Description)
	}
	if f.Vulnerability != nil && len(f.Vulnerability.IDs) > 0 {
		fmt.Fprintf(b, "- **Advisory:** %s\n", strings.Join(f.Vulnerability.IDs, ", "))
		if f.Vulnerability.Affected != "" {
			fmt.Fprintf(b, "- **Affected:** %s\n", f.Vulnerability.Affected)
		}
		if f.Vulnerability.FixedVersion != "" {
			fmt.Fprintf(b, "- **Fixed in:** %s\n", f.Vulnerability.FixedVersion)
		}
		if f.Vulnerability.CVSSScore != nil {
			fmt.Fprintf(b, "- **CVSS v3 base score:** %.1f (computed from the published vector)\n", *f.Vulnerability.CVSSScore)
		}
	}
	if f.Impact != "" {
		fmt.Fprintf(b, "- **Impact:** %s\n", oneLine(f.Impact))
	}
	if f.Remediation != "" {
		fmt.Fprintf(b, "- **Remediation:** %s\n", oneLine(f.Remediation))
	}
	if len(f.References) > 0 {
		fmt.Fprintf(b, "- **References:**\n")
		for _, ref := range f.References {
			fmt.Fprintf(b, "  - %s\n", ref)
		}
	}
	fmt.Fprintf(b, "\n")
}

// codeFence returns a backtick fence that cannot be closed by the content.
func codeFence(content string) string {
	longest, run := 0, 0
	for _, r := range content {
		if r == '`' {
			run++
			if run > longest {
				longest = run
			}
			continue
		}
		run = 0
	}
	if longest < 3 {
		longest = 2
	}
	return strings.Repeat("`", longest+1)
}

func networkSummary(rep *Report) string {
	if !rep.Network.Enabled {
		return "offline"
	}
	if len(rep.Network.Destinations) == 0 {
		return "online, no requests made"
	}
	return "sent package coordinates to " + strings.Join(rep.Network.Destinations, ", ")
}

func resultSummary(rep *Report) string {
	switch {
	case rep.Summary.Policy.Failed:
		return fmt.Sprintf("**FAIL** — %s (threshold `%s`)", rep.Summary.Policy.Reason, rep.Summary.Policy.FailOn)
	case rep.Summary.Incomplete:
		return fmt.Sprintf("**INCOMPLETE** — %d finding(s); checks were skipped", rep.Summary.Total)
	default:
		return fmt.Sprintf("PASS — no findings at or above `%s`", rep.Summary.Policy.FailOn)
	}
}

func escapeCell(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	s = strings.ReplaceAll(s, "\n", " ")
	return s
}

func oneLine(s string) string {
	return strings.Join(strings.Fields(s), " ")
}
